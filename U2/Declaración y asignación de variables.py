#Las variables son contenedores que nos permiten almacenar y manipular datos en nuestros programas
#Para declarar y asignar un valor a una variable en Python, utilizamos el operador de asignación =. El nombre de la variable va a la izquierda del operador, y el valor que deseas asignar va a la derecha. Por ejemplo:

nombre = "Juan"
edad = 25
altura = 1.75
es_estudiante = True

# En el ejemplo, hemos declarado y asignado valores a las variables nombre,
# edad, altura y es_estudiante. Python infiere automáticamente el tipo de datos
# de cada variable en función del valor asignado.
# También puedes asignar el mismo valor a múltiples variables en una sola línea utilizando el operador de asignación múltiple:

a = b = c = 10

# Siguiendo estas normas, algunos ejemplos de nombres de variables válidos son:
nombre_completo = "Ana"
edad_2 = 30
apellidos = "López"

# Algunos ejemplos de nombres de variables no válidos son:
# 1edad   # Comienza con un número
# nombre-completo   # Utiliza un guion en lugar de un guion bajo
# if   # Palabra clave reservada de Python